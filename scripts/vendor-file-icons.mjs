import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { basename, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const iconThemePackageDir = join(projectRoot, 'node_modules', 'material-icon-theme')
const outputDir = join(projectRoot, 'src', 'asset', 'file-icons')
const outputFile = join(outputDir, 'file-icons.gen.ts')

const MAPPING_TABLES = [
  { exportName: 'FILE_EXTENSIONS', section: 'fileExtensions' },
  { exportName: 'FILE_NAMES', section: 'fileNames' },
  { exportName: 'FOLDER_NAMES', section: 'folderNames' },
  { exportName: 'FOLDER_NAMES_EXPANDED', section: 'folderNamesExpanded' },
]

const DEFAULT_EXPORTS = [
  { exportName: 'DEFAULT_FILE_ICON', section: 'file' },
  { exportName: 'DEFAULT_FOLDER_ICON', section: 'folder' },
  { exportName: 'DEFAULT_FOLDER_EXPANDED_ICON', section: 'folderExpanded' },
]

const validateIconSvg = (params) => {
  const svgContents = params.svgContents.trim()
  if (!svgContents.startsWith('<svg') || !svgContents.endsWith('</svg>')) {
    return { error: `${params.svgFileName}: not a well-formed <svg>…</svg> document` }
  }
  return { svgContents }
}

const buildLowercasedTable = (params) => {
  return Object.entries(params.table).reduce((acc, [key, defName]) => {
    const lowerKey = key.toLowerCase()
    if (acc[lowerKey] !== undefined && acc[lowerKey] !== defName) {
      throw new Error(
        `${params.section}: keys "${key}" and existing "${lowerKey}" lowercase to same key with different defs`,
      )
    }
    acc[lowerKey] = defName
    return acc
  }, {})
}

const renderTable = (params) => {
  const entries = Object.keys(params.table)
    .sort()
    .map((key) => {
      return `  ${JSON.stringify(key)}: ${JSON.stringify(params.table[key])},`
    })
  return [
    `export const ${params.exportName}: Readonly<Partial<Record<string, FileIconKey>>> = {`,
    ...entries,
    '}',
    '',
  ].join('\n')
}

const main = async () => {
  const packageJson = JSON.parse(await readFile(join(iconThemePackageDir, 'package.json'), 'utf8'))
  const manifest = JSON.parse(await readFile(join(iconThemePackageDir, 'dist', 'material-icons.json'), 'utf8'))
  const iconDefinitions = manifest.iconDefinitions

  const referencedDefNames = new Set([
    ...MAPPING_TABLES.flatMap((table) => {
      return Object.values(manifest[table.section] ?? {})
    }),
    ...DEFAULT_EXPORTS.map((def) => {
      return manifest[def.section]
    }),
  ])
  const missingDefs = [...referencedDefNames].filter((defName) => {
    return !iconDefinitions[defName]
  })
  if (missingDefs.length > 0) {
    throw new Error(`iconDefinitions missing referenced defs: ${missingDefs.join(', ')}`)
  }

  const sortedDefNames = [...referencedDefNames].sort()
  const iconResults = await Promise.all(
    sortedDefNames.map(async (defName) => {
      const svgFileName = basename(iconDefinitions[defName].iconPath)
      const svgContents = await readFile(join(iconThemePackageDir, 'icons', svgFileName), 'utf8')
      return validateIconSvg({ svgContents, svgFileName })
    }),
  )
  const invalidIcons = iconResults.filter((result) => {
    return result.error
  })
  if (invalidIcons.length > 0) {
    throw new Error(`invalid svg sources:\n${invalidIcons.map((result) => result.error).join('\n')}`)
  }

  const defaultLines = DEFAULT_EXPORTS.map((def) => {
    return `export const ${def.exportName}: FileIconKey = ${JSON.stringify(manifest[def.section])}`
  })
  const tableOutputs = MAPPING_TABLES.map((table) => {
    return renderTable({
      exportName: table.exportName,
      table: buildLowercasedTable({ section: table.section, table: manifest[table.section] ?? {} }),
    })
  })

  const output = [
    `// Generated by scripts/vendor-file-icons.mjs — DO NOT EDIT.`,
    `// Source: material-icon-theme@${packageJson.version} (MIT, https://github.com/PKief/vscode-material-icon-theme)`,
    '',
    'export type FileIconKey =',
    ...sortedDefNames.map((defName) => {
      return `  | ${JSON.stringify(defName)}`
    }),
    '',
    'export const FILE_ICONS: Readonly<Record<FileIconKey, string>> = {',
    ...sortedDefNames.map((defName, index) => {
      return `  ${JSON.stringify(defName)}: ${JSON.stringify(iconResults[index].svgContents)},`
    }),
    '}',
    '',
    defaultLines.join('\n'),
    '',
    tableOutputs.join('\n'),
  ].join('\n')

  await mkdir(outputDir, { recursive: true })
  await writeFile(outputFile, output, 'utf8')

  const sizeKb = Math.round(Buffer.byteLength(output, 'utf8') / 102.4) / 10
  const tableSummary = MAPPING_TABLES.map((table) => {
    return `${manifest[table.section] ? Object.keys(manifest[table.section]).length : 0} ${table.exportName.toLowerCase()}`
  }).join(', ')
  console.log(`vendored ${sortedDefNames.length} icons (${tableSummary}) into ${outputFile} (${sizeKb} KB)`)
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
